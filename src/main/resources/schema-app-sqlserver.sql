IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'ix_doc_error_doc' AND object_id = OBJECT_ID(N'ocr.doc_error'))
    CREATE INDEX ix_doc_error_doc ON ocr.doc_error (doc_id, id);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'ix_doc_error_at' AND object_id = OBJECT_ID(N'ocr.doc_error'))
    CREATE INDEX ix_doc_error_at ON ocr.doc_error (created_at);

-- -----------------------------------------------------------------------------
-- doc_reprocess_request
-- -----------------------------------------------------------------------------
IF OBJECT_ID(N'ocr.doc_reprocess_request', N'U') IS NULL
CREATE TABLE ocr.doc_reprocess_request (
    id              BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT pk_doc_reprocess_request PRIMARY KEY,
    from_stage      VARCHAR(20)    NOT NULL,
    doc_id          BIGINT         NULL CONSTRAINT fk_doc_reprocess_request_job REFERENCES ocr.doc_job (id),
    doc_type        VARCHAR(50)    NULL,
    current_status  VARCHAR(20)    NULL,
    failed_stage    VARCHAR(20)    NULL,
    reason          NVARCHAR(1000) NULL,
    requested_by    NVARCHAR(100)  NOT NULL,
    requested_at    DATETIME2      NOT NULL CONSTRAINT df_doc_reprocess_request_at DEFAULT SYSDATETIME(),
    state           VARCHAR(20)    NOT NULL CONSTRAINT df_doc_reprocess_request_state DEFAULT 'PENDING',
    applied_count   INT            NULL,
    applied_at      DATETIME2      NULL,
    message         NVARCHAR(1000) NULL,
    CONSTRAINT ck_reprocess_stage CHECK (from_stage IN ('CLASSIFY', 'EXTRACT', 'MAP')),
    CONSTRAINT ck_reprocess_state CHECK (state IN ('PENDING', 'APPLIED', 'REJECTED'))
);

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'ix_doc_reprocess_state' AND object_id = OBJECT_ID(N'ocr.doc_reprocess_request'))
    CREATE INDEX ix_doc_reprocess_state ON ocr.doc_reprocess_request (state, id);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'ix_doc_reprocess_doc' AND object_id = OBJECT_ID(N'ocr.doc_reprocess_request'))
    CREATE INDEX ix_doc_reprocess_doc ON ocr.doc_reprocess_request (doc_id);

-- -----------------------------------------------------------------------------
-- v_doc_field_final: the value downstream systems should use (correction wins)
-- -----------------------------------------------------------------------------
CREATE OR ALTER VIEW ocr.v_doc_field_final AS
SELECT f.doc_id,
       f.doc_type,
       f.field_name,
       COALESCE(c.corrected_value, f.field_value)              AS final_value,
       CASE WHEN c.id IS NULL THEN 'MODEL' ELSE 'CORRECTED' END AS value_source,
       f.confidence,
       f.field_status,
       f.configured
FROM ocr.doc_field f
LEFT JOIN ocr.doc_field_correction c
       ON c.doc_id = f.doc_id AND c.field_name = f.field_name AND c.active = 1;
