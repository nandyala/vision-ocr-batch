    id            BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT pk_doc_error PRIMARY KEY,
    doc_id        BIGINT         NOT NULL CONSTRAINT fk_doc_error_job REFERENCES ocr.doc_job (id),
    stage         VARCHAR(20)    NOT NULL,
